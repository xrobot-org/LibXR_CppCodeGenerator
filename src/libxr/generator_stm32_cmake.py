# CMAKE_OBJCOPY 来自 CubeMX 的工具链文件。
# After linking, <project>.hex (Intel HEX) and <project>.bin (binary image) are made from the ELF
# in its directory; CMAKE_OBJCOPY comes from the CubeMX toolchain file.
FIRMWARE_BLOCK = """\
# Each link of the application also writes <project>.hex and <project>.bin next to the ELF.
add_custom_command(TARGET ${CMAKE_PROJECT_NAME} POST_BUILD
    WORKING_DIRECTORY $<TARGET_FILE_DIR:${CMAKE_PROJECT_NAME}>
    COMMAND ${CMAKE_OBJCOPY} --output-target ihex
        $<TARGET_FILE_NAME:${CMAKE_PROJECT_NAME}> ${CMAKE_PROJECT_NAME}.hex
    COMMAND ${CMAKE_OBJCOPY} --output-target binary --strip-all
        $<TARGET_FILE_NAME:${CMAKE_PROJECT_NAME}> ${CMAKE_PROJECT_NAME}.bin
    VERBATIM)"""

include_cmake_cmd = "include(${CMAKE_CURRENT_LIST_DIR}/cmake/LibXR.CMake)\n"

# 非注释行中任意写法的 include(...LibXR.CMake)。
# An include(...LibXR.CMake) in any spelling on a line that is not a comment.
_LIBXR_CMAKE_INCLUDE = re.compile(
    r"^[ \t]*include[ \t]*\([^)#\n]*LibXR\.CMake[^)\n]*\)", re.IGNORECASE | re.MULTILINE
)


def includes_libxr_cmake(content: str) -> bool:
    """CMakeLists.txt 的内容 content 是否已经 include LibXR.CMake。
    Whether content, the text of a CMakeLists.txt, already includes LibXR.CMake.

    include 的路径写法和大小写不限，最后一行没有换行也算；被注释掉的行不算。只比较整行文字时，
    这些写法会被再追加一次 include，LibXR 随之被 add_subdirectory 两次，CMake 配置失败。
    Any spelling of the path and any case count, also on a last line without a newline; a
    commented-out line does not. Comparing whole lines would append a second include for these
    spellings, and LibXR would then be added twice and fail the CMake configure.
    """
    return _LIBXR_CMAKE_INCLUDE.search(content) is not None


def project_uses_xrobot(input_directory: str) -> bool:
    """User/app_main.cpp 由 --xrobot 生成时为真；文件不存在时为假。
    True when User/app_main.cpp was generated with --xrobot; False when the file is missing.

    libxr stm32 setup 在接入 CMake 之前生成该文件。
    libxr stm32 setup generates that file before the CMake integration.
    """
    return uses_xrobot(os.path.join(input_directory, "User", "app_main.cpp"))


def uses_xrobot(app_main: str) -> bool:
    """源文件 app_main 由 libxr gen --xrobot 生成时为真；文件不存在时为假。
    True when the source file app_main was generated by libxr gen --xrobot; False when the
    file is missing.

    libxr gen --xrobot 在 User Code 区域之外 include xrobot_main.hpp。
    libxr gen --xrobot includes xrobot_main.hpp outside the User Code regions.
    """
    if not os.path.isfile(app_main):
        return False
    document = CppDocument.parse(read_text_with_fallback(app_main))
    regions = [region.body_span for region in document.user_regions()]
    for include in document.include_views():
        start = include.node.span.start
        if include.header == "xrobot_main.hpp" and not any(
            span.start <= start < span.end for span in regions
        ):
            return True
    return False


def read_text_with_fallback(path: str) -> str:
    """依次尝试以 UTF-8、UTF-8-SIG 和 GB18030 解码读取文本文件，返回第一个成功的结果。
    Read a text file with the first of UTF-8, UTF-8-SIG and GB18030 that decodes it.

    Raises:
        UnicodeDecodeError: 三种编码都无法解码该文件。
            None of the three encodings decodes the file.
    """
    for enc in ("utf-8", "utf-8-sig", "gb18030"):
        try:
            return Path(path).read_text(encoding=enc)
        except UnicodeDecodeError:
            continue
    return Path(path).read_text(encoding="utf-8")


# --------------------------
# LibXR.CMake 的结构 / Structure of LibXR.CMake
# --------------------------
def _rule(title: str) -> str:
    """块标题行：# ---- <title> ---- 补满 RULE_WIDTH 列。
    A block title line: # ---- <title> followed by dashes up to RULE_WIDTH columns.
    """
    head = f"# ---- {title} "
    return head + "-" * max(4, RULE_WIDTH - len(head))


def render_libxr_cmake(settings: str, kept: str = "") -> str:
    """LibXR.CMake 的完整内容：settings 是 “Project settings” 块的内容，kept 是末尾 “Kept” 块的
    内容（为空时没有这个块）。
    The complete content of LibXR.CMake: settings is the content of the "Project settings"
    block and kept the content of the "Kept" block at the end (without that block when empty).
    """
    parts = [
        GENERATED_LINE,
        "",
        _rule(SETTINGS_TITLE),
        settings.strip("\n"),
        "",
        _rule(LIBXR_TITLE),
        LIBXR_BLOCK,
        "",
        _rule(APPLICATION_TITLE),
        APPLICATION_BLOCK,
        "",
        _rule(OPTIMIZATION_TITLE),
        OPTIMIZATION_BLOCK,
        "",
        _rule(FIRMWARE_TITLE),
        FIRMWARE_BLOCK,
    ]
    if kept.strip():
        parts += ["", _rule(KEPT_TITLE), kept.strip("\n")]
    return "\n".join(parts) + "\n"


def _setting_lines(opt_debug: str, opt_release: str, user_sources: str) -> list[str]:
    """“Project settings” 块中 LIBXR_USER_SOURCES_GLOB、LIBXR_OPT_DEBUG 和 LIBXR_OPT_RELEASE 的
    设置行，前两项带说明注释。
    The setting lines of LIBXR_USER_SOURCES_GLOB, LIBXR_OPT_DEBUG and LIBXR_OPT_RELEASE in the
    "Project settings" block, the first two with their comment.
    """
    return [
        '# User sources of the application; "" when CMakeLists.txt adds them itself.\n'
        f'set(LIBXR_USER_SOURCES_GLOB "{user_sources}")',
        "# Optimization level of the application in Debug builds and of everything in Release "
        'builds;\n# "" keeps the level of the toolchain file.\n'
        f'set(LIBXR_OPT_DEBUG "{opt_debug}")',
        f'set(LIBXR_OPT_RELEASE "{opt_release}")',
    ]


def default_settings(system: str, opt_debug: str, opt_release: str) -> str:
    """新工程的 “Project settings” 块：LIBXR_SYSTEM、LIBXR_DRIVER、User 源文件和两个优化级别。
    The "Project settings" block of a new project: LIBXR_SYSTEM, LIBXR_DRIVER, the User sources
    and the two optimization levels.
    """
    lines = [f"set(LIBXR_SYSTEM {system})", "set(LIBXR_DRIVER st)"]
    lines += _setting_lines(opt_debug, opt_release, USER_SOURCES_GLOB)
    return "\n".join(lines) + "\n"


def split_blocks(content: str) -> dict[str, str] | None:
    """新格式 LibXR.CMake 的各块：{标题: 内容}；第一行不是 GENERATED_LINE（旧格式）时为 None。
    The blocks of a LibXR.CMake in the current format as {title: content}; None when the first
    line is not GENERATED_LINE, an earlier format.
    """
    lines = content.split("\n")
    if not lines or lines[0].strip() != GENERATED_LINE:
        return None
    blocks: dict[str, list[str]] = {}
    current = None
    for line in lines[1:]:
        title = re.fullmatch(r"# ---- (.+?) -{4,}", line.rstrip())
        if title:
            current = title.group(1)
            blocks[current] = []
        elif current is not None:
            blocks[current].append(line)
    return {title: "\n".join(body).strip("\n") for title, body in blocks.items()}


# set(<name> <value>) 的写法：值取到右括号或行尾的注释之前。
# The spelling of set(<name> <value>): the value runs up to the closing parenthesis or a
# comment at the end of the line.
def _setting(name: str) -> re.Pattern:
    """匹配设置块中 set(name ...) 一行的正则；第 1 组为 set( 和名字，第 2 组为值。
    The regular expression for a set(name ...) line of the settings block; group 1 is set( and
    the name, group 2 the value.
    """
    return re.compile(rf"^([ \t]*set[ \t]*\([ \t]*{name}[ \t]+)([^)#\n]*?)([ \t]*\))", re.MULTILINE)


def _set_system(settings: str, system: str) -> str:
    """把设置块中所有 set(LIBXR_SYSTEM ...) 的值换成 system；没有这一行时插在块的开头。
    Replace the value of every set(LIBXR_SYSTEM ...) of the settings block with system; the
    line is inserted at the top of the block when it is missing.
    """
    pattern = _setting("LIBXR_SYSTEM")
    if pattern.search(settings):
        return pattern.sub(lambda m: f"{m.group(1)}{system}{m.group(3)}", settings)
    return f"set(LIBXR_SYSTEM {system})\n" + settings


def _add_missing(settings: str, name: str, line: str, after: str | None = None) -> str:
    """设置块中没有 set(name ...) 时加入 line：放在 set(after ...) 之后，没有 after 时放在块的末尾。
    Add line when the settings block has no set(name ...): after set(after ...), or at the end
    of the block without after.
    """
    if _setting(name).search(settings):
        return settings
    if after:
        match = _setting(after).search(settings)
        if match:
            end = settings.find("\n", match.end())
            end = len(settings) if end < 0 else end + 1
            return settings[:end] + line + "\n" + settings[end:]
    return settings.rstrip("\n") + "\n" + line + "\n"


def _follow_xrobot_choice(settings: str, use_xrobot: bool, line: str = "") -> str:
    """让设置块中的 XROBOT_MODULES_DIR 与入口源文件的选择一致，返回新内容。
    Make XROBOT_MODULES_DIR in the settings block agree with the choice of the entry source and
    return the new content.

    使用 XRobot 而没有这一设置时，在 LIBXR_DRIVER 之后加入 line（默认 XROBOT_MODULES_DIR_LINE）；
    不使用 XRobot 而有这一设置时删除它。每次改动都记录一条说明。
    With XRobot and no such setting, line (XROBOT_MODULES_DIR_LINE by default) is added after
    LIBXR_DRIVER; without XRobot, an existing setting is removed. Each change is logged.
    """
    line = line or XROBOT_MODULES_DIR_LINE
    setting = re.compile(r"^[ \t]*set\s*\(\s*XROBOT_MODULES_DIR\b[^\n]*\n?", re.MULTILINE)
    if use_xrobot and not setting.search(settings):
        logging.info(
            tr(
                f"LibXR.CMake: added {line}, as User/app_main.cpp uses XRobot",
                f"LibXR.CMake：User/app_main.cpp 使用了 XRobot，已加入 {line}",
            )
        )
        return _add_missing(settings, "XROBOT_MODULES_DIR", line, "LIBXR_DRIVER")
    if not use_xrobot and setting.search(settings):
        logging.info(
            tr(
                "LibXR.CMake: removed XROBOT_MODULES_DIR, as User/app_main.cpp does not use XRobot",
                "LibXR.CMake：User/app_main.cpp 没有使用 XRobot，已删除 XROBOT_MODULES_DIR",
            )
        )
        return setting.sub("", settings)
    return settings


def _complete_settings(
    settings: str,
    system: str,
    use_xrobot: bool,
    opt_debug: str,
    opt_release: str,
    xrobot_line: str = "",
) -> str:
    """补全并校正设置块：LIBXR_SYSTEM 取检测到的系统，缺少的 LIBXR_DRIVER 和优化级别补上默认值，
    XROBOT_MODULES_DIR 与入口源文件的选择一致；其余内容不动。
    Complete and correct the settings block: LIBXR_SYSTEM takes the detected system, a missing
    LIBXR_DRIVER or optimization level gets its default, XROBOT_MODULES_DIR agrees with the
    choice of the entry source, and everything else stays.
    """
    settings = _set_system(settings, system)
    settings = _add_missing(settings, "LIBXR_DRIVER", "set(LIBXR_DRIVER st)", "LIBXR_SYSTEM")
    settings = _follow_xrobot_choice(settings, use_xrobot, xrobot_line)
    sources, debug, release = _setting_lines(opt_debug, opt_release, USER_SOURCES_GLOB)
    settings = _add_missing(settings, "LIBXR_USER_SOURCES_GLOB", sources)
    settings = _add_missing(settings, "LIBXR_OPT_DEBUG", debug)
    return _add_missing(settings, "LIBXR_OPT_RELEASE", release)


